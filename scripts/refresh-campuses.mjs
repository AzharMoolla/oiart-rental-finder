import {mkdir,writeFile} from 'node:fs/promises';

const source='https://www.ontario.ca/my-career-journey/find-postsecondary-institutions/';
const html=await fetch(source).then(r=>{if(!r.ok)throw Error(`Ontario HTTP ${r.status}`);return r.text();});
// The official public locator publishes its read-only dataset configuration.
// Consume that dataset at build time; never ship its access token in this app.
const token=html.match(/mapConfig=\{token:"([^"]+)"/)?.[1];
const dataset=html.match(/datasetId:"([^"]+)"/)?.[1];
if(!token||!dataset)throw Error('Official locator configuration changed');
const response=await fetch(`https://api.mapbox.com/datasets/v1/mcu-career-portal/${dataset}/features?access_token=${encodeURIComponent(token)}`);
if(!response.ok)throw Error(`Official dataset HTTP ${response.status}`);
const data=await response.json();
await mkdir('.local-tools',{recursive:true});
await writeFile('.local-tools/ontario-institutions-source.json',JSON.stringify(data,null,2));
const campuses=data.features.map(f=>{
  const p=f.properties,[lon,lat]=f.geometry.coordinates;
  return {id:'on-'+p.id,institution:p['institution-name'].trim(),name:p['campus-name'].trim(),city:p.City.trim(),
    type:p.Type,main:p['Main-campus']==='Y',address:p['Address-full'].trim(),lat,lon,
    url:p['campus-web-url']||p['institution-web-url-en']||p['institution-web-url-fr']};
});
campuses.push({id:'oiart',institution:'OIART',name:'London',city:'London',type:'Career college',main:true,
  address:'502 Newbold Street, London, ON',lat:42.937,lon:-81.215,url:'https://www.oiart.org/'});
campuses.sort((a,b)=>a.institution.localeCompare(b.institution)||Number(b.main)-Number(a.main)||a.name.localeCompare(b.name));
if(campuses.length<100||new Set(campuses.map(c=>c.id)).size!==campuses.length||campuses.some(c=>!Number.isFinite(c.lat)||!Number.isFinite(c.lon)))throw Error('Campus dataset failed validation');
await writeFile('campus-data.js','// Generated by scripts/refresh-campuses.mjs from the official Ontario locator.\n'+
  'const CAMPUS_CATALOGUE = '+JSON.stringify({source,checked:new Date().toISOString().slice(0,10),campuses},null,2)+';\n');
console.log(JSON.stringify({campuses:campuses.length,main:campuses.filter(c=>c.main).length,source}));
